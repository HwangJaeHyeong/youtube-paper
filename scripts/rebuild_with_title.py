"""Rebuild a shorts video with spoken title (no silence-skip), then re-upload as scheduled.

Usage: rebuild_with_title.py <slug> <publish_at_rfc3339>
  e.g.  rebuild_with_title.py 2111.06377 2026-04-30T18:00:00+09:00
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src import tts
from src.config import AUDIO_DIR, SCRIPTS_DIR, VIDEOS_DIR
from src.pipeline import _generate_video
from src.upload import youtube as yt_upload
from src.video import audio_merger


def main(slug: str, publish_at: str) -> None:
    shorts_slug = f"{slug}-shorts"
    script_json = SCRIPTS_DIR / f"{shorts_slug}.json"
    data = json.loads(script_json.read_text(encoding="utf-8"))
    title_hook = data.get("title_hook") or data.get("paper_title", "")
    paper_title = data.get("paper_title", "")

    # Ensure index 0 is __TITLE__ with spoken title text.
    lines_ = data["script"]
    if lines_ and lines_[0].get("visual_ref") == "__TITLE__":
        lines_[0]["text"] = title_hook
        lines_[0]["skip_subtitle"] = True
        lines_[0]["pause_after_ms"] = 400
        lines_[0]["emotion"] = "neutral"
    else:
        host = lines_[0].get("speaker", "민재")
        lines_.insert(0, {
            "section": "intro", "speaker": host, "text": title_hook,
            "emotion": "neutral", "pause_after_ms": 400,
            "visual_ref": "__TITLE__", "skip_subtitle": True,
        })
    script_json.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"intro line: {lines_[0]['text']}", flush=True)

    # Wipe TTS lines, merged mp3, title card, header.
    line_dir = AUDIO_DIR / shorts_slug / "lines"
    line_dir.mkdir(parents=True, exist_ok=True)
    for w in line_dir.glob("*.wav"):
        w.unlink()
    mp3 = AUDIO_DIR / shorts_slug / f"{shorts_slug}.mp3"
    if mp3.exists():
        mp3.unlink()
    crops_dir = AUDIO_DIR / shorts_slug / "crops"
    for n in ("__TITLE__.png", "__HEADER__.png"):
        p = crops_dir / n
        if p.exists():
            p.unlink()

    # TTS for ALL lines (no silence-skip on __TITLE__).
    pairs = []
    for i, line in enumerate(data["script"]):
        wav = line_dir / f"{i:03d}_{line['speaker']}.wav"
        if not wav.exists():
            tts.synthesize(line["text"], line["speaker"], wav, emotion=line.get("emotion", "neutral"))
        pairs.append((wav, int(line.get("pause_after_ms", 200))))
        print(f"TTS {i:02d}: {line['text'][:70]}", flush=True)
    audio_merger.merge(pairs, mp3)

    # Build video.
    out_mp4 = _generate_video(shorts_slug, script_json, mp3, is_shorts=True)
    print(json.dumps({"mp4": str(out_mp4), "orientation": "shorts"}), flush=True)

    # Upload as scheduled.
    primary_tag = (data.get("primary_tag") or "").replace(" ", "")
    verdict = data.get("rating", {}).get("verdict", "")
    official_url = data.get("metadata", {}).get("official_url", "")
    description = (
        f"{paper_title}\n\n한줄평: {verdict}\n\n"
        f"📄 논문 원문: {official_url}\n\n"
        f"#논문리뷰 #AI #{primary_tag} #Shorts\n\n"
        f"Generated by PaperCast."
    )
    tags = ["논문리뷰", "AI", "딥러닝", "컴퓨터비전", primary_tag, "Shorts"]
    vid = yt_upload.upload(
        out_mp4, title_hook, description, tags,
        privacy_status="public", is_shorts=True,
        publish_at=publish_at,
    )
    print(json.dumps({"video_id": vid, "url": f"https://www.youtube.com/watch?v={vid}"}), flush=True)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
