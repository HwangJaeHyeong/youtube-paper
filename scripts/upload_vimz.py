"""Upload VIMz (PoPETs 2024) shorts as private."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.config import SCRIPTS_DIR, VIDEOS_DIR
from src.upload import youtube as yt_upload

SLUG = "vimz-shorts"


def _clean_title(title_hook: str) -> str:
    return title_hook.replace("**", "").replace("\n", " ").strip()


def main() -> None:
    script_json = SCRIPTS_DIR / f"{SLUG}.json"
    data = json.loads(script_json.read_text(encoding="utf-8"))
    paper_title = data.get("paper_title", "")
    title_hook = data.get("title_hook") or paper_title
    yt_title = _clean_title(title_hook)
    official_url = data.get("metadata", {}).get("official_url", "")
    primary_tag = (data.get("primary_tag") or "VIMz").replace(" ", "")
    verdict = data.get("rating", {}).get("verdict", "")

    base_hashtags = ["논문리뷰", "암호학", "영지식증명", "ZK", "딥페이크", "PoPETs"]
    if primary_tag not in base_hashtags:
        base_hashtags.append(primary_tag)
    base_hashtags.append("Shorts")
    hashtag_line = " ".join(f"#{t}" for t in base_hashtags)

    description = (
        f"{paper_title}\n\n"
        f"한줄평: {verdict}\n\n"
        f"📄 논문 원문: {official_url}\n\n"
        f"{hashtag_line}\n\n"
        f"Generated by PaperCast."
    )
    tags = ["논문리뷰", "암호학", "영지식증명", "ZK", "zkSNARK", "딥페이크",
            "PoPETs", "Cryptography", "Shorts"]
    if primary_tag not in tags:
        tags.append(primary_tag)

    out_mp4 = VIDEOS_DIR / f"{SLUG}.mp4"
    if not out_mp4.exists():
        raise SystemExit(f"missing video: {out_mp4}")

    print(f"title       : {yt_title}")
    print(f"file        : {out_mp4}")
    print(f"privacy     : private")
    print(f"tags        : {tags}")
    print("-" * 60)
    print(description)
    print("-" * 60)

    vid = yt_upload.upload(
        out_mp4, yt_title, description, tags,
        privacy_status="private", is_shorts=True,
    )
    print(json.dumps({"video_id": vid, "url": f"https://www.youtube.com/watch?v={vid}"},
                     ensure_ascii=False))


if __name__ == "__main__":
    main()
