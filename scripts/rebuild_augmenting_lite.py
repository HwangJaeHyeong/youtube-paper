"""Minimal rebuild: reuse existing audio + user-edited crops, just re-compose video + upload."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.config import AUDIO_DIR, PAPERS_DIR, SCRIPTS_DIR, VIDEOS_DIR, SHORTS_RESOLUTION
from src import tts
from src.video import audio_merger, composer, figure_cropper, figure_indexer, subtitle, title_card
from src.upload import youtube as yt_upload


def main() -> None:
    slug = "augmenting-length-chi2026"
    shorts_slug = f"{slug}-shorts"
    pdf = PAPERS_DIR / "augmenting.pdf"
    script_json = SCRIPTS_DIR / f"{shorts_slug}.json"
    data = json.loads(script_json.read_text(encoding="utf-8"))

    # Ensure TTS for current script (regen any missing / reorder-friendly)
    line_dir = AUDIO_DIR / shorts_slug / "lines"
    line_dir.mkdir(parents=True, exist_ok=True)
    wavs, pairs = [], []
    for i, line in enumerate(data["script"]):
        wav = line_dir / f"{i:03d}_{line['speaker']}.wav"
        if not wav.exists():
            print(f"TTS {i:02d} {line['speaker']}", flush=True)
            tts.synthesize(line["text"], line["speaker"], wav, emotion=line.get("emotion", "neutral"))
        wavs.append(wav); pairs.append((wav, int(line.get("pause_after_ms", 200))))
    mp3 = AUDIO_DIR / shorts_slug / f"{shorts_slug}.mp3"
    audio_merger.merge(pairs, mp3)

    # Collect crops — reuse whatever's in crops/ (user may have replaced images)
    crops_dir = AUDIO_DIR / shorts_slug / "crops"
    crops: dict = {}
    for png in crops_dir.glob("*.png"):
        key = png.stem.replace("_", " ")
        if png.stem == "__TITLE__":
            key = "__TITLE__"
        crops[key] = png
    print(f"crops available: {sorted(crops.keys())}", flush=True)

    # Refresh title card in case hook changed
    intro_title = data.get("title_hook") or data.get("paper_title", slug)
    tc = crops_dir / "__TITLE__.png"
    title_card.render_title_card(intro_title, tc, size=SHORTS_RESOLUTION)
    crops["__TITLE__"] = tc

    cover = AUDIO_DIR / shorts_slug / "cover.png"
    if not cover.exists():
        title_card.render_cover(cover)

    pages = []
    line_is_cover = [figure_cropper.normalize_ref(l.get("visual_ref")) not in crops for l in data["script"]]
    ass = AUDIO_DIR / shorts_slug / f"{shorts_slug}.ass"
    subtitle.build_ass(data["script"], wavs, ass, line_is_cover=line_is_cover)
    segments = composer.build_segments_v2(data["script"], wavs, pages, figure_index={}, crops=crops, fallback_img=cover)
    print(f"segments: {len(segments)}", flush=True)
    out_mp4 = VIDEOS_DIR / f"{shorts_slug}.mp4"
    composer.compose_shorts(mp3, ass, pages, segments, out_mp4)

    title = "Augmenting Perceived Length of Handheld Controllers: Effects of Object Handle Properties"
    title_hook = data.get("title_hook") or title
    primary_tag = (data.get("primary_tag") or "HCI").replace(" ", "")
    verdict = data.get("rating", {}).get("verdict", "")
    official_url = data.get("metadata", {}).get("official_url", "") or ""
    description = (
        f"{title}\n\n한줄평: {verdict}\n\n"
        f"📄 논문 원문: {official_url}\n\n"
        f"#논문리뷰 #HCI #햅틱스 #VR #{primary_tag} #Shorts\n\nGenerated by PaperCast."
    )
    tags = ["논문리뷰", "HCI", "햅틱스", "VR", "CHI", "POSTECH", primary_tag, "Shorts"]
    vid = yt_upload.upload(
        out_mp4, title_hook, description, tags,
        privacy_status="public", is_shorts=True,
        publish_at="2026-04-26T21:00:00+09:00",
    )
    print(f"video_id: {vid}", flush=True)


if __name__ == "__main__":
    main()
